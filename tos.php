<h2>Điều Khoản và Dịch Vụ</h2>
<t>Vui lòng đọc kỹ các điều khoản dưới đây trước khi đồng ý</t>

<h3>Phần 1 - Định Nghĩa</h3>

<ul>
	<li>a. <b>Chúng Tôi</b> nghĩa là tác giả và người điều hành <i>Công Cụ Này</i>. Tức là <b>Team DHS</b></li>
	<li>b. <b>Công Cụ Này</b> nghĩa là công cụ hiện tại bạn đang sử dụng của Chúng Tôi. Tức là <b>Deal Hunter Suite</b></li>
	<li>c. <b>Người Dùng</b> nghĩa là cá nhân hoặc thực thể đang sử dụng phần mềm của Chúng Tôi. Tức là <b>Bạn</b></li>
	<li>d. <b>Sàn Thương Mại Điện Tử</b> nghĩa là các sàn giao dịch thương mại trực tuyến có liên quan tới Công Cụ Này</li>
</ul>

<h3>Phần 2 - Lời Tuyên Bố</h3>

<ul>
	<li>a. <b>Chúng tôi</b> sẽ không có đảm bảo, lời hứa và/hoặc những tuyên bố, bất kể là nói rõ hay ngầm hiểu, được đưa ra về tính chân thực, chuẩn mực và chính xác hoặc các tính chất khác của các Deal cũng như chức năng của Công Cụ Này trên các Sàn Thương Mại Điện Tử.</li>
	<li>b. <b>Chúng tôi</b> không thể và sẽ không đảm bảo rằng người dùng sẽ nhận được deal tốt hoặc chắc chắn mua được deal tốt.</li>
	<li>c. <b>Chúng tôi</b> sẽ không chịu trách nhiệm về bất kể mất mát hay thiệt hại nào (trực tiếp, gián tiếp, hệ quả...) có thể xảy ra từ những vấn đề có thể phát sinh trong việc sử dụng Công Cụ Này (nếu có) bao gồm cả trách nhiệm về pháp lý.</li>
</ul>

<h3>Phần 3 - Mục đích và Chấm dứt Dịch vụ</h3>

<ul>
	<li>Toàn bộ nội dung cũng như chức năng của Công Cụ Này tạo ra từ nhu cầu của người sử dụng và phục vụ mục đích của người sử dụng. Nên chúng tôi không chịu trách nhiệm về bất cứ hành động cũng như cách sử dụng của người dùng.</li>
	<li>Chúng tôi hoàn toàn có thể chấm dứt dịch vụ nếu có bất cứ khiếu nại (nếu có) liên quan đến dịch vụ mà không cần thông báo trước.</li>
</ul>

